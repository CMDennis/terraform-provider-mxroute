#!/usr/bin/env python3
"""Generate/check the pinned API inventory. This command never uses the network."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

import yaml

ROOT = Path(__file__).resolve().parents[1]
METHODS = {"get", "put", "post", "delete", "options", "head", "patch", "trace"}


def read_json(path):
    return json.loads(path.read_text())


def build_inventory(root):
    manifest = read_json(root / "api/baseline.json")
    snapshot = root / manifest["snapshot"]
    digest = hashlib.sha256(snapshot.read_bytes()).hexdigest()
    if digest != manifest["sha256"]:
        raise ValueError("snapshot checksum mismatch; review upstream changes before replacing the baseline")
    checksum = root / (manifest["snapshot"] + ".sha256")
    if checksum.read_text() != f"{digest}  {snapshot.name}\n":
        raise ValueError("checksum sidecar does not match the baseline")
    spec = yaml.safe_load(snapshot.read_text())
    if spec["info"]["version"] != manifest["api_version"] or spec["openapi"] != manifest["openapi_version"]:
        raise ValueError("API version differs from baseline")
    coverage = read_json(root / "api/coverage.json")
    operations = {}
    for path, path_item in spec["paths"].items():
        for method, operation in path_item.items():
            if method in METHODS:
                operations[f"{method.upper()} {path}"] = (path_item, operation)
    if set(coverage) != set(operations):
        raise ValueError(f"coverage differs: unmapped={sorted(set(operations) - set(coverage))}; "
                         f"obsolete={sorted(set(coverage) - set(operations))}")
    if len(operations) != manifest["operation_count"] or len(spec["paths"]) != manifest["path_count"]:
        raise ValueError("operation/path counts differ from approved baseline")
    clients = [item["client_method"] for item in coverage.values()]
    if len(clients) != len(set(clients)):
        raise ValueError("client methods must be unique per operation")
    rows = []
    for key, (path_item, operation) in sorted(operations.items()):
        mapped = coverage[key]
        for field in ("terraform", "tests", "documentation", "status", "client_method", "phase", "contract_issue_ids"):
            if not mapped.get(field):
                raise ValueError(f"{key}: missing coverage field {field}")
        responses = {}
        for status, response in operation["responses"].items():
            responses[str(status)] = response
        rows.append({
            "key": key, **mapped,
            "summary": operation["summary"],
            "description": operation.get("description", ""),
            "parameters": path_item.get("parameters", []) + operation.get("parameters", []),
            "request_body": operation.get("requestBody"),
            "responses": responses,
        })
    # Preserve all schemas, references, defaults, units, nullable fields and shared descriptions.
    # References are local to this generated document, just as in the pinned OpenAPI file.
    return {
        "baseline": manifest,
        "info": spec["info"],
        "servers": spec.get("servers", []),
        "tags": spec.get("tags", []),
        "security": spec.get("security", []),
        "components": spec["components"],
        "operations": rows,
    }


def render_markdown(inventory):
    lines = [
        "# Operation inventory", "",
        "Generated by `python scripts/api_inventory.py`; edit `api/coverage.json` to change mappings.", "",
        f"Pinned baseline: {inventory['baseline']['operation_count']} operations across "
        f"{inventory['baseline']['path_count']} paths. Per-operation implementation status is recorded "
        "below. Client and implemented Terraform lifecycle tests run against local mocks. "
        "Every operation has a Terraform surface and generated reference docs. Phase 7 verified fourteen ordinary-account reads; lifecycle and reseller compatibility remain live-unverified.", "",
        "Full request/response schemas, parameters, defaults, nullable fields and local references "
        "are retained in [operations.json](../../api/operations.json). Sparse responses remain "
        "sparse; no invented success payloads or pagination have been added.", "",
        "| Method/path | Client method | Terraform surface | Phase | Tests | Documentation | Contracts / blockers | Status |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in inventory["operations"]:
        lines.append("| " + " | ".join([
            f"`{row['key']}`", f"`{row['client_method']}`", "; ".join(row["terraform"]),
            str(row["phase"]), "; ".join(row["tests"]), "; ".join(row["documentation"]),
            ", ".join(row["contract_issue_ids"]) + ("; blocks stabilization: " + ", ".join(row["feature_blockers"]) if row["feature_blockers"] else ""), row["status"],
        ]) + " |")
    return "\n".join(lines) + "\n"


def validate_fixtures(root, inventory):
    fixtures = read_json(root / "testdata/contracts/scenarios.json")
    cases = fixtures["cases"]
    keys = {row["key"] for row in inventory["operations"]}
    issue_ids = set(re.findall(r"\bC\d{2}\b", (root / "docs/design/api-contracts.md").read_text()))
    if fixtures["source"]["openapi_snapshot"] != inventory["baseline"]["snapshot"]:
        raise ValueError("fixture source differs from the pinned snapshot")
    for row in inventory["operations"]:
        if not set(row["contract_issue_ids"] + row["feature_blockers"]) <= issue_ids:
            raise ValueError(f"unknown contract issue in {row['key']}")
    ids = set()
    for case in cases:
        if case["id"] in ids:
            raise ValueError(f"duplicate fixture id: {case['id']}")
        ids.add(case["id"])
        if case["operation_key"] not in keys:
            raise ValueError(f"fixture {case['id']} references an unknown operation")
        method, template = case["operation_key"].split(" ", 1)
        # Concrete request paths must match their declared method/path obligation.
        pattern = re.sub(r"\\\{[^}]+\\\}", "[^/]+", re.escape(template))
        if method != case["method"] or not re.fullmatch(pattern, case["path"]):
            raise ValueError(f"fixture {case['id']} does not match its operation key")
        response = case["response"]
        if not isinstance(response["status"], int) or not 100 <= response["status"] <= 599:
            raise ValueError(f"fixture {case['id']} has an invalid HTTP status")
        if response["status"] == 204 and response["body"] is not None:
            raise ValueError(f"fixture {case['id']}: 204 must have no body")
        if not isinstance(response["headers"], dict):
            raise ValueError(f"fixture {case['id']} has invalid headers")
        encoding = response.get("body_encoding")
        if encoding not in {"empty", "json", "raw"}:
            raise ValueError(f"fixture {case['id']} lacks an explicit body encoding")
        if (encoding == "empty") != (response["body"] is None):
            raise ValueError(f"fixture {case['id']} has inconsistent body encoding")
        if encoding == "raw" and not isinstance(response["body"], str):
            raise ValueError(f"fixture {case['id']} raw body must be text")
        if not case.get("expectation") or not case.get("contract_issue_ids"):
            raise ValueError(f"fixture {case['id']} lacks an expectation or contract issue")
        if not set(case["contract_issue_ids"]) <= issue_ids:
            raise ValueError(f"fixture {case['id']} references an unknown contract issue")
    if not cases:
        raise ValueError("contract fixtures are empty")
    return len(cases)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on stale generated inventory")
    args = parser.parse_args()
    try:
        inventory = build_inventory(ROOT)
        count = validate_fixtures(ROOT, inventory)
        outputs = {
            ROOT / "api/operations.json": json.dumps(inventory, indent=2, ensure_ascii=False) + "\n",
            ROOT / "docs/design/operation-inventory.md": render_markdown(inventory),
        }
        for path, expected in outputs.items():
            if args.check:
                if not path.exists() or path.read_text() != expected:
                    raise ValueError(f"stale generated file: {path.relative_to(ROOT)}")
            else:
                path.write_text(expected)
        print(f"Verified {len(inventory['operations'])} operations, pinned checksum, and {count} synthetic cases (offline).")
    except (ValueError, KeyError, OSError, yaml.YAMLError) as exc:
        print(f"inventory error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
